export function toolGroupsFor(diagramType: string): ToolGroup[] {
  return TOOLBOXES[diagramType] ?? [annotationGroup];
}

export function findTool(id: string): Tool | undefined {
  for (const groups of Object.values(TOOLBOXES)) for (const g of groups) for (const t of g.tools) if (t.id === id) return t;
  return undefined;
}

