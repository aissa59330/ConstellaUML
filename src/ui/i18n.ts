const dicts: Record<Lang, Record<I18nKey, string>> = { fr, en };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("constella.lang");
    if (saved === "fr" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.startsWith("fr") ? "fr" : "en";
}

const [lang, setLangSignal] = createSignal<Lang>(initialLang());
export { lang };

export function setLang(l: Lang): void {
  setLangSignal(l);
  try {
    localStorage.setItem("constella.lang", l);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = l;
}

/** Translates `key`, filling `{name}` placeholders. Reactive (reads `lang`). */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = (dicts[lang()] as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

