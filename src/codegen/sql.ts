// SQL DDL from ERD entities, for MySQL/MariaDB, PostgreSQL and SQLite.
import type { Element } from "../core/element";
import type { Repository } from "../core/repository";
import type { GenOptions, SqlDialect } from "./types";

/** Entities under `base` (a data model, or the project: every data model). */
export function collectEntities(base: Element): Element[] {
  const out: Element[] = [];
  const visit = (el: Element) => {
    for (const c of (el.ownedElements ?? []) as Element[]) {
      if (c._type === "ERDEntity") out.push(c);
      else if (c._type === "ERDDataModel" || c._type === "Project" || /Package|Model$/.test(c._type)) visit(c);
    }
  };
  if (base._type === "ERDEntity") return [base];
  visit(base);
  return out;
}

export function quoteIdent(name: string, dialect: SqlDialect): string {
  return dialect === "mysql" ? `\`${name.replace(/`/g, "``")}\`` : `"${name.replace(/"/g, '""')}"`;
}

/** Column type for the dialect (SQLite and PostgreSQL spellings of a few common types). */
function sqlType(c: Element, dialect: SqlDialect): string {
  let t = String(c.type ?? "").trim().toUpperCase() || "VARCHAR";
  const len = String(c.length ?? "").trim();
  if (dialect === "postgresql") {
    if (t === "DATETIME") t = "TIMESTAMP";
    if (t === "DOUBLE") t = "DOUBLE PRECISION";
    if (t === "TINYINT" && len === "1") return "BOOLEAN";
    if (t === "LONGTEXT" || t === "MEDIUMTEXT") t = "TEXT";
    if (t === "BLOB" || t === "LONGBLOB") t = "BYTEA";
  }
  return len && !t.includes("(") ? `${t}(${len})` : t;
}

export function generateSql(repo: Repository, base: Element, o: GenOptions): string {
  const dialect = o.dialect ?? "mysql";
  const q = (n: string) => quoteIdent(n, dialect);
  const entities = collectEntities(base);
  const tableOf = (col: Element) => repo.parentOf(col);

  // Parents first so that inline foreign keys refer to existing tables.
  const order: Element[] = [];
  const state = new Map<Element, number>();
  const visit = (e: Element) => {
    if (state.get(e)) return;
    state.set(e, 1);
    for (const c of (e.columns ?? []) as Element[]) {
      const target = c.referenceTo ? tableOf(repo.deref(c.referenceTo) ?? ({} as Element)) : undefined;
      if (target && target !== e && entities.includes(target) && !state.get(target)) visit(target);
    }
    order.push(e);
  };
  entities.forEach(visit);

  const out: string[] = [`-- Generated by ConstellaUML (${dialect})`, ""];
  if (o.dropTables) {
    for (const e of [...order].reverse()) out.push(`DROP TABLE IF EXISTS ${q(e.name)};`);
    out.push("");
  }
  const created = new Set<Element>();
  const deferred: string[] = [];
  for (const e of order) {
    const cols = (e.columns ?? []) as Element[];
    const lines: string[] = [];
    const pk = cols.filter((c) => c.primaryKey);
    for (const c of cols) {
      let def = `${q(c.name)} ${sqlType(c, dialect)}`;
      if (!c.nullable || c.primaryKey) def += " NOT NULL";
      if (c.unique && !c.primaryKey) def += " UNIQUE";
      if (c.defaultValue) def += ` DEFAULT ${c.defaultValue}`;
      lines.push(def);
    }
    if (pk.length) lines.push(`PRIMARY KEY (${pk.map((c) => q(c.name)).join(", ")})`);
    for (const c of cols) {
      const ref = c.referenceTo ? repo.deref(c.referenceTo) : undefined;
      const target = ref ? tableOf(ref) : undefined;
      if (!ref || !target) continue;
      const fk = `FOREIGN KEY (${q(c.name)}) REFERENCES ${q(target.name)} (${q(ref.name)})`;
      // A reference to a table created later (cycle) is added afterwards, except in SQLite.
      if (created.has(target) || target === e || dialect === "sqlite") lines.push(fk);
      else deferred.push(`ALTER TABLE ${q(e.name)} ADD CONSTRAINT ${q(`fk_${e.name}_${c.name}`)} ${fk};`);
    }
    if (o.docComments && e.documentation) out.push(...String(e.documentation).trim().split(/\r?\n/).map((l) => `-- ${l}`));
    out.push(`CREATE TABLE ${q(e.name)} (`, lines.map((l) => `  ${l}`).join(",\n"), ");", "");
    created.add(e);
  }
  if (deferred.length) out.push(...deferred, "");
  return out.join("\n");
}
